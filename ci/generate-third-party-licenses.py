def find_license_files(pkg: dict) -> list[pathlib.Path]:
    pkg_dir = pathlib.Path(pkg["manifest_path"]).parent
    found: list[pathlib.Path] = []
    if pkg.get("license_file"):
        explicit = pkg_dir / pkg["license_file"]
        if explicit.is_file():
            found.append(explicit)
    for child in sorted(pkg_dir.iterdir(), key=lambda p: p.name):
        if child.is_file() and any(k in child.name.upper() for k in LICENSE_KEYWORDS):
            if child not in found:
                found.append(child)
    return found


def main() -> int:
    out_path = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else "THIRD_PARTY_LICENSES.txt")
    repo_root = pathlib.Path(__file__).resolve().parent.parent

    raw = subprocess.check_output(
        ["cargo", "metadata", "--format-version", "1", "--locked"],
        cwd=repo_root,
    )
    meta = json.loads(raw)
    workspace_ids = set(meta["workspace_members"])
    packages = sorted(
        (p for p in meta["packages"] if p["id"] not in workspace_ids),
        key=lambda p: (p["name"], p["version"]),
    )
    if not packages:
        raise RuntimeError("No third-party packages found in cargo metadata")

    apache_path = repo_root / "assets" / "fonts" / "LICENSE_APACHE.txt"
    if apache_path.is_file():
        STANDARD_TEXTS["Apache-2.0"] = apache_path.read_text(encoding="utf-8", errors="replace").strip()

    for pkg in packages:
        if pkg["name"] in ("colored", "nucleo-matcher"):
            for f in find_license_files(pkg):
                STANDARD_TEXTS["MPL-2.0"] = f.read_text(encoding="utf-8", errors="replace").strip()
                break

    groups: dict[str, dict] = {}
    order: list[str] = []

    def add_group(text: str, pkg_entry: str) -> None:
        norm = text.strip()
        digest = hashlib.sha256(norm.encode("utf-8")).hexdigest()
        if digest not in groups:
            groups[digest] = {"text": norm, "packages": []}
            order.append(digest)
        if pkg_entry not in groups[digest]["packages"]:
            groups[digest]["packages"].append(pkg_entry)

    mpl_packages: list[tuple[str, str, str]] = []

    for pkg in packages:
        name = pkg["name"]
        version = pkg["version"]
        lic = pkg.get("license") or "Custom"
        authors = ", ".join(pkg.get("authors") or [])
        repo = pkg.get("repository") or pkg.get("homepage") or f"https://crates.io/crates/{name}/{version}"
        entry = f"{name} {version} ({lic}) - {repo}"
        if authors:
            entry += f" - Authors: {authors}"

        if "MPL-2.0" in lic:
            mpl_packages.append((name, version, repo))

        files = find_license_files(pkg)
        if files:
            for f in files:
                text = f.read_text(encoding="utf-8", errors="replace")
                add_group(text, f"{entry} [{f.name}]")
        else:
            matched = False
            for spdx_key, std_text in STANDARD_TEXTS.items():
                if spdx_key in lic:
                    add_group(std_text, entry)
                    matched = True
            if not matched:
                add_group(f"SPDX-License-Identifier: {lic}", entry)

    lines: list[str] = [
        "THIRD-PARTY SOFTWARE NOTICES AND LICENSES",
        "=========================================",
        "",
        f"This file lists the {len(packages)} third-party Rust crates in the wakterm Cargo workspace lockfile",
        "along with their copyright notices and license texts.",
        "",
    ]

    if mpl_packages:
        lines.extend(
            [
                "Mozilla Public License 2.0 (MPL-2.0) Source Code Notice",
                "-------------------------------------------------------",
                "The following unmodified crates are distributed under the Mozilla Public License 2.0.",
                "Their source code is available from crates.io and their upstream repositories:",
            ]
        )
        for name, version, repo in mpl_packages:
            lines.append(
                f"  - {name} {version}: https://static.crates.io/crates/{name}/{name}-{version}.crate ({repo})"
            )
        lines.append("")

    lines.extend(
        [
            "GNU Lesser General Public License v2.1 (LGPL-2.1-only) Notice",
            "-------------------------------------------------------------",
            "On Linux (X11), wakterm links xcb-imdkit 0.3.0 (https://github.com/wakamex/xcb-imdkit-rs,",
            "commit 212330f7c6c37794d78061a773e8f4f9e4785bbb) under the GNU Lesser General Public",
            "License v2.1. The complete corresponding source code for xcb-imdkit is published with each",
            "release as wakterm-vX.Y.Z-xcb-imdkit-source.tar.gz, and the LGPL-2.1 text is included in",
            "COPYING.LGPLv2.1 and below.",
            "",
        ]
    )

    for idx, digest in enumerate(order, 1):
        grp = groups[digest]
        lines.append("=" * 78)
        lines.append(f"License Group {idx} ({len(grp['packages'])} crate(s))")
        lines.append("-" * 78)
        for pkg_line in grp["packages"]:
            lines.append(f"  * {pkg_line}")
        lines.append("-" * 78)
        lines.append(grp["text"])
        lines.append("")

    out_path.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {out_path} ({len(packages)} crates, {len(order)} license groups, {out_path.stat().st_size} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
